from typing import Any, TypedDict

from langgraph.graph import END, START, StateGraph


class InvoiceAgentState(TypedDict, total=False):
    """
    Shared state passed through the invoice review agent graph.

    The graph does not make final financial decisions.
    It produces a grounded recommendation for a human reviewer.
    """

    invoice_id: int

    # Existing Day 16 / Day 17 analysis data
    analysis_result: dict[str, Any]
    policy_evidence: list[dict[str, Any]]

    # Completeness stage
    completeness_score: int
    missing_fields: list[str]
    completeness_status: str

    # Risk stage
    duplicate_risk: bool
    possible_duplicate_invoice_id: int | None
    risk_level: str
    risk_reasons: list[str]

    # Policy stage
    policy_context_available: bool
    policy_evidence_count: int

    # Recommendation stage
    recommendation: str
    recommendation_reasons: list[str]

    # Human-in-the-loop stage
    human_review_required: bool
    final_decision_allowed: bool

    # Explainability / execution trace
    agent_trace: list[str]


def analysis_intake_node(
    state: InvoiceAgentState,
) -> dict[str, Any]:
    """
    Read the existing local invoice analysis result.

    Day 16 already performs:
    - document extraction
    - completeness analysis
    - duplicate detection
    - deterministic risk analysis

    The LangGraph workflow orchestrates those results rather
    than duplicating the underlying analysis logic.
    """

    analysis = state.get(
        "analysis_result",
        {},
    )

    trace = list(
        state.get(
            "agent_trace",
            [],
        )
    )

    trace.append(
        "Loaded local invoice analysis."
    )

    return {
        "completeness_score": int(
            analysis.get(
                "completeness_score",
                0,
            )
            or 0
        ),
        "missing_fields": list(
            analysis.get(
                "missing_fields",
                [],
            )
            or []
        ),
        "duplicate_risk": bool(
            analysis.get(
                "duplicate_risk",
                False,
            )
        ),
        "possible_duplicate_invoice_id":
            analysis.get(
                "possible_duplicate_invoice_id"
            ),
        "risk_level": (
            analysis.get(
                "risk_level",
                "needs_review",
            )
            or "needs_review"
        ),
        "risk_reasons": list(
            analysis.get(
                "risk_reasons",
                [],
            )
            or []
        ),
        "agent_trace": trace,
    }


def completeness_node(
    state: InvoiceAgentState,
) -> dict[str, Any]:
    """
    Evaluate whether the invoice appears complete enough
    for a human reviewer to continue.
    """

    score = state.get(
        "completeness_score",
        0,
    )

    missing_fields = state.get(
        "missing_fields",
        [],
    )

    if missing_fields:
        status = "incomplete"

    elif score >= 100:
        status = "complete"

    else:
        status = "needs_review"

    trace = list(
        state.get(
            "agent_trace",
            [],
        )
    )

    trace.append(
        (
            "Completeness check: "
            f"{status} ({score}%)."
        )
    )

    return {
        "completeness_status": status,
        "agent_trace": trace,
    }


def risk_node(
    state: InvoiceAgentState,
) -> dict[str, Any]:
    """
    Normalize the deterministic duplicate and risk signals
    generated by the existing invoice analysis service.
    """

    duplicate_risk = state.get(
        "duplicate_risk",
        False,
    )

    risk_level = state.get(
        "risk_level",
        "needs_review",
    )

    risk_reasons = list(
        state.get(
            "risk_reasons",
            [],
        )
    )

    if (
        duplicate_risk
        and "Possible duplicate invoice detected."
        not in risk_reasons
    ):
        risk_reasons.append(
            "Possible duplicate invoice detected."
        )

    trace = list(
        state.get(
            "agent_trace",
            [],
        )
    )

    trace.append(
        (
            "Risk check: "
            f"{risk_level}; "
            f"duplicate risk={duplicate_risk}."
        )
    )

    return {
        "risk_reasons": risk_reasons,
        "agent_trace": trace,
    }


def policy_context_node(
    state: InvoiceAgentState,
) -> dict[str, Any]:
    """
    Inspect the policy evidence retrieved by the Day 17
    local RAG pipeline.

    This node does not invent policy information.
    It only records whether grounded policy evidence exists.
    """

    evidence = state.get(
        "policy_evidence",
        [],
    )

    evidence_count = len(
        evidence
    )

    trace = list(
        state.get(
            "agent_trace",
            [],
        )
    )

    if evidence_count > 0:
        trace.append(
            (
                "Policy RAG check: "
                f"{evidence_count} relevant "
                "policy chunk(s) available."
            )
        )

    else:
        trace.append(
            (
                "Policy RAG check: "
                "no sufficiently relevant "
                "policy evidence retrieved."
            )
        )

    return {
        "policy_context_available":
            evidence_count > 0,
        "policy_evidence_count":
            evidence_count,
        "agent_trace": trace,
    }


def recommendation_node(
    state: InvoiceAgentState,
) -> dict[str, Any]:
    """
    Generate a deterministic review recommendation.

    This is deliberately rule-based and local.
    It does not approve or reject invoices.
    """

    completeness_status = state.get(
        "completeness_status",
        "needs_review",
    )

    duplicate_risk = state.get(
        "duplicate_risk",
        False,
    )

    risk_level = state.get(
        "risk_level",
        "needs_review",
    )

    missing_fields = state.get(
        "missing_fields",
        [],
    )

    risk_reasons = state.get(
        "risk_reasons",
        [],
    )

    policy_available = state.get(
        "policy_context_available",
        False,
    )

    reasons: list[str] = []

    # Highest-priority condition:
    # suspected duplicate.
    if duplicate_risk:
        recommendation = "high_attention"

        reasons.append(
            (
                "The invoice may duplicate "
                "an existing invoice."
            )
        )

    # Missing required information.
    elif completeness_status == "incomplete":
        recommendation = "needs_documents"

        reasons.append(
            (
                "Required invoice information "
                "or supporting documentation "
                "is missing."
            )
        )

    # Existing deterministic analysis found
    # a high-risk condition.
    elif risk_level == "high_attention":
        recommendation = "high_attention"

        reasons.append(
            (
                "The deterministic risk analysis "
                "identified a high-attention condition."
            )
        )

    # Medium / review-level conditions.
    elif risk_level == "needs_review":
        recommendation = "needs_review"

        reasons.append(
            (
                "The invoice contains conditions "
                "that should be reviewed manually."
            )
        )

    else:
        recommendation = "low_risk"

        reasons.append(
            (
                "No major automated risk signal "
                "was detected."
            )
        )

    if missing_fields:
        reasons.append(
            (
                "Missing fields: "
                + ", ".join(
                    str(field)
                    for field in missing_fields
                )
                + "."
            )
        )

    for reason in risk_reasons:
        if reason not in reasons:
            reasons.append(
                str(reason)
            )

    if policy_available:
        reasons.append(
            (
                "Relevant nonprofit policy evidence "
                "was retrieved for reviewer reference."
            )
        )

    else:
        reasons.append(
            (
                "No sufficiently relevant policy "
                "evidence was retrieved; manual "
                "policy verification may be needed."
            )
        )

    trace = list(
        state.get(
            "agent_trace",
            [],
        )
    )

    trace.append(
        (
            "Recommendation generated: "
            f"{recommendation}."
        )
    )

    return {
        "recommendation":
            recommendation,
        "recommendation_reasons":
            reasons,
        "agent_trace":
            trace,
    }


def human_review_node(
    state: InvoiceAgentState,
) -> dict[str, Any]:
    """
    Enforce the human-in-the-loop boundary.

    The agent may recommend actions, but it is never allowed
    to make the final approve/reject/payment decision.
    """

    trace = list(
        state.get(
            "agent_trace",
            [],
        )
    )

    trace.append(
        (
            "Human review required before "
            "any final financial decision."
        )
    )

    return {
        "human_review_required": True,
        "final_decision_allowed": False,
        "agent_trace": trace,
    }


def build_invoice_agent_graph():
    """
    Build and compile the local invoice review agent graph.
    """

    builder = StateGraph(
        InvoiceAgentState
    )

    builder.add_node(
        "analysis_intake",
        analysis_intake_node,
    )

    builder.add_node(
        "completeness_check",
        completeness_node,
    )

    builder.add_node(
        "risk_check",
        risk_node,
    )

    builder.add_node(
        "policy_context",
        policy_context_node,
    )

    builder.add_node(
        "recommendation",
        recommendation_node,
    )

    builder.add_node(
        "human_review",
        human_review_node,
    )

    builder.add_edge(
        START,
        "analysis_intake",
    )

    builder.add_edge(
        "analysis_intake",
        "completeness_check",
    )

    builder.add_edge(
        "completeness_check",
        "risk_check",
    )

    builder.add_edge(
        "risk_check",
        "policy_context",
    )

    builder.add_edge(
        "policy_context",
        "recommendation",
    )

    builder.add_edge(
        "recommendation",
        "human_review",
    )

    builder.add_edge(
        "human_review",
        END,
    )

    return builder.compile()


invoice_agent_graph = (
    build_invoice_agent_graph()
)


def run_invoice_agent(
    invoice_id: int,
    analysis_result: dict[str, Any],
    policy_evidence: list[dict[str, Any]]
    | None = None,
) -> InvoiceAgentState:
    """
    Run the local LangGraph invoice review workflow.

    Parameters
    ----------
    invoice_id:
        Invoice being reviewed.

    analysis_result:
        Existing Day 16/17 local invoice analysis output.

    policy_evidence:
        Existing Day 17 RAG evidence.

    Returns
    -------
    InvoiceAgentState:
        Final graph state containing the recommendation,
        reasoning summary, trace, and human-review guardrail.
    """

    initial_state: InvoiceAgentState = {
        "invoice_id": invoice_id,
        "analysis_result":
            analysis_result,
        "policy_evidence":
            policy_evidence or [],
        "agent_trace": [],
    }

    result = invoice_agent_graph.invoke(
        initial_state
    )

    return result